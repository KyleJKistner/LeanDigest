SCHEMA = 'leanglish.dependency-cone-plan/v1'
SHARD = 'leanglish.dependency-cone-shard/v1'
SUMMARY = 'leanglish.dependency-cone-summary/v1'
DENOMINATOR = 'dependency-cone-level-1'
REPORT = 'dependency-cone-shard.json'
# The budgets of the original-environment theorem campaign (proof_campaign.run_module).
EXECUTION = {'lean_version': '4.34.1', 'build_timeout': 3600, 'extract_timeout': 900,
             'max_heartbeats': 2_000_000, 'wall_seconds': 12_000}
PILOT_SHARDS = 8
PILOT_MAX_ELAPSED = 1800
MATRIX_LIMIT = 256
PROJECT = re.compile(r'(?:_private\.)?OAI\.')
PROOF_MEMBER = re.compile(r'Leanglish/proofs/([0-9a-f]{24})/(snapshot\.json|receipt\.json)')
WORKER_MEMBER = re.compile(r'Leanglish/original-evidence/proof-workers/([0-9a-f]{64})/(original-proof-worker\.json|proofs\.json)')
ORIGINAL_MEMBERS = {'Leanglish/original-evidence/plan.json': 'original_plan',
                    'Leanglish/original-evidence/environment.json': 'environment'}
# First match wins. Name rules are conventions, not Lean facts; anything they do
# not catch is planned as 'unknown-kind' and the exporter decides at extraction.
EXCLUSIONS = [
    ('not-addressable-by-exporter', re.compile(r'^_private\.|(?:^|\.)\d|«'),
     'The exporter resolves a name with String.toName, which cannot form the numeric or escaped components of a mangled private name.'),
    ('compiler-matcher-or-recursor', re.compile(r'\.(?:match_\d+(?:_\d+)*|casesOn|recOn|rec|brecOn|binductionOn|below|ibelow|noConfusion|noConfusionType)$'),
     'Generated by the compiler for pattern matching or structural recursion; not a stated lemma.'),
    ('instance-by-name', re.compile(r'\.inst[A-Z][^.]*$'),
     "Lean's generated instance name; supplied by instance resolution. A user-named instance is not detected here and is decided by the exporter."),
    ('constructor-by-name', re.compile(r'\.mk$'),
     'Structure constructor name; a constructor has no proof body to read.'),
]
REASONS = {'documented-theorem-target': 'A documented theorem target belongs to the 536-target denominator, not the cone.',
           'documented-definition': 'A documented definition reference is not a proof obligation.',
           **{r: text for r, _, text in EXCLUSIONS}}
AUXILIARY = re.compile(r'(?:^|\.)_?proof_\d+(?:_\d+)*$')
# Worker outcomes. Lean-decided outcomes end an attempt; the rest are gaps in this run.
READ = {'reading-generated'}
DECLINED = {'not-proof-valued', 'no-proof-body', 'disallowed-axiom'}
ATTEMPT_FAILURES = {'frame-budget-exceeded', 'unknown-constant', 'extraction-timeout',
                     'rendering-failed', 'extraction-failed'}
INFRASTRUCTURE = {'build-failed', 'build-timeout', 'source-missing', 'source-changed',
                  'toolchain-unavailable', 'environment-invalidated'}
NOT_ATTEMPTED = {'not-attempted', 'deadline-not-attempted'}
TRANSIENT = {'extracting'}
ROW_STATUSES = READ | DECLINED | ATTEMPT_FAILURES | INFRASTRUCTURE | NOT_ATTEMPTED | TRANSIENT
SHARD_STATUSES = {'preflight', 'running', 'complete', 'partial', 'failed'}
MARKERS = [('Expected a proof-valued declaration', 'not-proof-valued'),
           ('Expected a declaration with a proof body', 'no-proof-body'),
           ('Disallowed axiom', 'disallowed-axiom'),
           ('Narrative frame budget exceeded', 'frame-budget-exceeded')]
FLAGS = {'counts_toward_documented_target_coverage': False, 'english_formally_certified': False,
         'observations_authenticated': False}


def module_id(module: str) -> str:
    return sha256(module.encode()).hexdigest()[:24]


def lemma_id(module: str, name: str) -> str:
    return sha256((module+'\0'+name).encode()).hexdigest()[:24]


def hint(name: str) -> str | None:
    return 'compiler-abstracted-proof' if AUXILIARY.search(name) else None


def exclusion(name: str) -> str | None:
    return next((reason for reason, rule, _ in EXCLUSIONS if rule.search(name)), None)


def excluded_reason(name: str, original: dict) -> str | None:
    """Documented targets and definitions keep their own denominator; then the name rules."""
    if any(name in t['theorem_names'] for t in original['tasks'] if t['kind'] == 'comparator'):
        return 'documented-theorem-target'
    if any(name in t['definition_names'] for t in original['tasks'] if t['kind'] == 'comparator'):
        return 'documented-definition'
    return exclusion(name)


def read_archive(data: bytes, expected_sha256: str) -> dict:
    """Retained snapshots, receipts and original-environment evidence of one pinned release."""
    if sha256(data).hexdigest() != expected_sha256:
        raise ValueError('Release archive digest does not match the pinned release')
    proofs, workers, original = {}, {}, {}
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        names = z.namelist()
        if len(set(names)) != len(names):
            raise ValueError('Duplicate release archive member')
        for name in sorted(names):
            if (m := PROOF_MEMBER.fullmatch(name)):
                proofs.setdefault(m[1], {})[m[2]] = z.read(name)
            elif (m := WORKER_MEMBER.fullmatch(name)):
                workers.setdefault(m[1], {})[m[2]] = z.read(name)
            elif name in ORIGINAL_MEMBERS:
                original[ORIGINAL_MEMBERS[name]] = strict_json(z.read(name))
    if set(original) != set(ORIGINAL_MEMBERS.values()):
        raise ValueError('The release lacks its original plan or environment audit')
    return {'proofs': proofs, 'workers': workers, **original}


def retained_readings(proofs: dict, original_plan: dict) -> list[dict]:
    """Identity comes from each receipt; it must name a documented target and bind its snapshot."""
    targets = universe(original_plan)
    rows = []
    for ident, files in sorted(proofs.items()):
        if set(files) != {'snapshot.json', 'receipt.json'}:
            raise ValueError('A retained reading needs its snapshot and receipt: '+ident)
        record, receipt = strict_json(files['snapshot.json']), strict_json(files['receipt.json'])
        snap = Snapshot(record)
        key = (receipt.get('module'), receipt.get('theorem'))
        if (key not in targets or record['theorem'] != key[1] or receipt.get('status') != 'passed' or
            receipt.get('snapshot_sha256') != snap.sha256 or record['lean_version'] != EXECUTION['lean_version'] or
            lemma_id(*key) != ident):
            raise ValueError('Retained reading identity is inconsistent: '+ident)
        rows.append({'id': ident, 'module': key[0], 'theorem': key[1], 'snapshot_sha256': snap.sha256,
                     'file_sha256': data_digest(files['snapshot.json']), 'frames': snap.frames})
    if not rows or len({r['theorem'] for r in rows}) != len(rows):
        raise ValueError('Empty or duplicate retained reading inventory')
    return rows


def worker_evidence(workers: dict) -> list[dict]:
    """Retained original-environment theorem workers; used to choose the pilot, never as acceptance."""
    rows = []
    for key, files in sorted(workers.items()):
        if set(files) != {'original-proof-worker.json', 'proofs.json'}:
            raise ValueError('Incomplete retained proof-worker evidence')
        report, proofs = strict_json(files['original-proof-worker.json']), strict_json(files['proofs.json'])
        before, after = report.get('environment_before'), report.get('environment_after')
        elapsed = proofs.get('elapsed_seconds')
        rows.append({'module': report.get('module'), 'status': report.get('status'),
                     'elapsed_seconds': elapsed if type(elapsed) in (int, float) else None,
                     'environment_sha256': before.get('environment_sha256') if isinstance(before, dict) and before == after else None,
                     'worker_report_sha256': data_digest(files['original-proof-worker.json'])})
    return rows


def choose_pilot(shards: list[dict], evidence: list[dict], environment_sha256: str) -> dict:
    """Most planned lemmas among modules already built and read in this exact environment."""
    seen = {}
    for w in evidence:
        if (w['status'] == 'complete' and w['environment_sha256'] == environment_sha256 and
            w['elapsed_seconds'] is not None and w['elapsed_seconds'] <= PILOT_MAX_ELAPSED):
            best = seen.get(w['module'])
            if best is None or (w['elapsed_seconds'], w['worker_report_sha256']) < (best['elapsed_seconds'], best['worker_report_sha256']):
                seen[w['module']] = w
    ranked = sorted((s for s in shards if s['module'] in seen), key=lambda s: (-len(s['lemmas']), s['module']))
    chosen = ranked[:PILOT_SHARDS]
    return {'rule': f'The {PILOT_SHARDS} environment modules with the most planned lemmas among those whose '
                    'retained original-environment theorem worker completed, with identical before/after '
                    f'environment audits equal to this plan, in at most {PILOT_MAX_ELAPSED} seconds; ties by module name.',
            'eligible_shards': len(ranked), 'shards': [s['id'] for s in chosen],
            'lemmas': sum(len(s['lemmas']) for s in chosen),
            'evidence': [{'module': s['module'], 'elapsed_seconds': seen[s['module']]['elapsed_seconds'],
                          'worker_report_sha256': seen[s['module']]['worker_report_sha256']} for s in chosen]}


def homes(planned: list[str], cited_by: dict[str, list[str]], module_of: dict[str, str]) -> dict[str, str]:
    """The citing module that cites the most planned lemmas, ties by module name."""
    citing = {n: {module_of[i] for i in cited_by[n]} for n in planned}
    load = Counter(m for n in planned for m in citing[n])
    return {n: min(citing[n], key=lambda m: (-load[m], m)) for n in planned}


def make_plan(inputs: dict, identity: dict) -> dict:
    """Deterministic level-1 plan from one pinned release (see read_archive)."""
    original, environment = inputs['original_plan'], inputs['environment']
    validate_original(original)
    check_environment(original, environment)
    readings = retained_readings(inputs['proofs'], original)
    module_of = {r['id']: r['module'] for r in readings}
    read_names = {r['theorem']: r['id'] for r in readings}
    cited: dict[str, dict] = {}
    for r in readings:
        for f in r['frames']:
            if PROJECT.match(f['head']):
                c = cited.setdefault(f['head'], {'citations': 0, 'cited_by': set()})
                c['citations'] += 1
                c['cited_by'].add(r['id'])
    row = lambda n: {'name': n, 'citations': cited[n]['citations'], 'cited_by': sorted(cited[n]['cited_by'])}
    already, excluded, planned = [], [], []
    for name in sorted(cited):
        if name in read_names:
            already.append({**row(name), 'reading': read_names[name]})
            continue
        reason = excluded_reason(name, original)
        if reason:
            excluded.append({**row(name), 'reason': reason})
        else:
            planned.append(name)
    home = homes(planned, {n: cited[n]['cited_by'] for n in planned}, module_of)
    shards = []
    for module in sorted(set(home.values())):
        source = 'lean/'+module.replace('.', '/')+'.lean'
        if source not in original['source_files']:
            raise ValueError('Environment module is not in the original source inventory: '+module)
        shards.append({'id': module_id(module), 'module': module, 'source': source,
                       'source_sha256': original['source_files'][source],
                       'lemmas': [{**row(n), 'kind': 'unknown-kind', 'hint': hint(n)} for n in planned if home[n] == module]})
    patterns = {r: rule.pattern for r, rule, _ in EXCLUSIONS}
    plan = {'schema': SCHEMA, 'upstream_commit': PIN, 'level': 1, 'denominator_name': DENOMINATOR,
            'inputs': {'archive': identity, 'readings': len(readings),
                       'corpus_sha256': data_digest('\n'.join(sorted(r['file_sha256'] for r in readings))),
                       'original_plan_sha256': original['plan_sha256'],
                       'original_environment_sha256': environment['environment_sha256'],
                       'retained_proof_workers': len(inputs['workers'])},
            'execution': {**EXECUTION, 'exporter_sha256': data_digest(exporter_source())},
            'environment_rule': 'Each planned lemma is extracted after importing the module of a retained reading '
                                'that cites it: the citing module that cites the most planned lemmas, ties by name.',
            'kind_rule': "Planned lemmas are 'unknown-kind': the exporter accepts only proof-valued declarations "
                         'with a proof body, and the worker records what it decided.',
            'exclusion_rules': [{'reason': r, 'pattern': patterns.get(r), 'rationale': t} for r, t in REASONS.items()],
            'readings': [{k: r[k] for k in ('id', 'module', 'theorem', 'snapshot_sha256')} for r in readings],
            'already_read': already, 'excluded': excluded, 'shards': shards,
            'pilot': choose_pilot(shards, worker_evidence(inputs['workers']), environment['environment_sha256']),
            **FLAGS}
    plan['denominator'] = denominator(plan)
    plan['plan_sha256'] = digest(plan)
    return validate_plan(plan)


def denominator(plan: dict) -> dict:
    lemmas = [l for s in plan['shards'] for l in s['lemmas']]
    rows = plan['already_read']+plan['excluded']+lemmas
    return {'cited_constants': len(rows), 'citing_frames': sum(r['citations'] for r in rows),
            'citing_readings': len({i for r in rows for i in r['cited_by']}),
            'already_read': len(plan['already_read']), 'excluded': len(plan['excluded']),
            'excluded_by_reason': dict(sorted(Counter(r['reason'] for r in plan['excluded']).items())),
            'planned_lemmas': len(lemmas), 'environment_modules': len(plan['shards']),
            'planned_compiler_abstracted_proofs': sum(l['hint'] is not None for l in lemmas),
            'full_dispatch_parts': -(-len(plan['shards'])//MATRIX_LIMIT)}


def validate_plan(plan: dict) -> dict:
    """Internal consistency of a plan; its digest binds content, not authorship."""
    if (not isinstance(plan, dict) or plan.get('schema') != SCHEMA or plan.get('upstream_commit') != PIN or
        plan.get('level') != 1 or plan.get('denominator_name') != DENOMINATOR or
        any(plan.get(k) is not v for k, v in FLAGS.items()) or
        plan.get('plan_sha256') != digest({k: v for k, v in plan.items() if k != 'plan_sha256'})):
        raise ValueError('Wrong dependency-cone plan identity or binding')
    e = plan['execution']
    if ({k: e.get(k) for k in EXECUTION} != EXECUTION or set(e) != set(EXECUTION) | {'exporter_sha256'} or
        not re.fullmatch(r'[a-f0-9]{64}', str(e['exporter_sha256']))):
        raise ValueError('Unsupported dependency-cone execution limits')
    reading_ids = [r['id'] for r in plan['readings']]
    if (reading_ids != sorted(set(reading_ids)) or plan['inputs']['readings'] != len(reading_ids) or
        any(lemma_id(r['module'], r['theorem']) != r['id'] for r in plan['readings'])):
        raise ValueError('Plan reading inventory is inconsistent')
    read_names = {r['theorem']: r['id'] for r in plan['readings']}
    names = []
    for r in plan['already_read']:
        if read_names.get(r['name']) != r['reading']:
            raise ValueError('Already-read lemma does not name its reading')
    for r in plan['excluded']:
        if r['reason'] not in REASONS or (r['reason'] in {x[0] for x in EXCLUSIONS} and exclusion(r['name']) != r['reason']):
            raise ValueError('Unknown or inconsistent exclusion reason')
    modules = [s['module'] for s in plan['shards']]
    if modules != sorted(set(modules)):
        raise ValueError('Shards must be unique environment modules in name order')
    for s in plan['shards']:
        if (s['id'] != module_id(s['module']) or s['source'] != 'lean/'+s['module'].replace('.', '/')+'.lean' or
            not re.fullmatch(r'[a-f0-9]{64}', str(s['source_sha256'])) or not s['lemmas'] or
            [l['name'] for l in s['lemmas']] != sorted({l['name'] for l in s['lemmas']})):
            raise ValueError('Invalid dependency-cone shard')
        for l in s['lemmas']:
            if (set(l) != {'name', 'citations', 'cited_by', 'kind', 'hint'} or l['kind'] != 'unknown-kind' or l['hint'] != hint(l['name']) or
                exclusion(l['name']) or l['name'] in read_names):
                raise ValueError('Planned lemma is excluded, already read or malformed')
    for r in plan['already_read']+plan['excluded']+[l for s in plan['shards'] for l in s['lemmas']]:
        names.append(r['name'])
        if (not PROJECT.match(r['name']) or type(r['citations']) is not int or r['citations'] < len(r['cited_by']) or
            not r['cited_by'] or r['cited_by'] != sorted(set(r['cited_by'])) or not set(r['cited_by']) <= set(reading_ids)):
            raise ValueError('Malformed cited-constant row')
    if len(set(names)) != len(names) or plan['denominator'] != denominator(plan):
        raise ValueError('Cone denominator does not reconcile')
    planned = {l['name']: (l['cited_by'], s['module']) for s in plan['shards'] for l in s['lemmas']}
    chosen = homes(sorted(planned), {n: v[0] for n, v in planned.items()}, {r['id']: r['module'] for r in plan['readings']})
    if any(chosen[n] != v[1] for n, v in planned.items()):
        raise ValueError('A shard is not the planned environment module of its lemma')
    by = {s['id']: s for s in plan['shards']}
    pilot = plan['pilot']['shards']
    if (len(set(pilot)) != len(pilot) or not set(pilot) <= set(by) or len(pilot) > PILOT_SHARDS or
        plan['pilot']['lemmas'] != sum(len(by[i]['lemmas']) for i in pilot) or
        [e['module'] for e in plan['pilot']['evidence']] != [by[i]['module'] for i in pilot]):
        raise ValueError('Pilot is not a bounded, evidenced subset of the plan')
    return plan


def scope_shards(plan: dict, scope: str) -> list[dict]:
    """'pilot', or 'full-K': the K-th consecutive block of at most 256 shards (a matrix limit)."""
    by = {s['id']: s for s in plan['shards']}
    if scope == 'pilot':
        return [by[i] for i in plan['pilot']['shards']]
    m = re.fullmatch(r'full-([1-9][0-9]*)', scope)
    if not m or int(m[1]) > plan['denominator']['full_dispatch_parts']:
        raise ValueError('Unknown dependency-cone dispatch scope')
    k = int(m[1])-1
    return plan['shards'][k*MATRIX_LIMIT:(k+1)*MATRIX_LIMIT]


def bind_original(plan: dict, original: dict, environment: dict) -> None:
    validate_plan(plan)
    validate_original(original)
    check_environment(original, environment)
    if (plan['inputs']['original_plan_sha256'] != original['plan_sha256'] or
        plan['inputs']['original_environment_sha256'] != environment['environment_sha256']):
        raise ValueError('The cone plan belongs to another original environment')
    if (any(excluded_reason(l['name'], original) for s in plan['shards'] for l in s['lemmas']) or
        any(excluded_reason(r['name'], original) != r['reason'] for r in plan['excluded']) or
        any(original['source_files'].get(s['source']) != s['source_sha256'] for s in plan['shards'])):
        raise ValueError('The cone plan disagrees with the original target or source inventory')


def classify(directory: Path) -> str:
    """Name a failed extraction from its retained run observation, never from prose."""
    run = strict_json((directory/'run.json').read_text(encoding='utf-8')) if (directory/'run.json').is_file() else None
    if run is None:
        return 'extraction-failed'
    if run.get('reason') == 'timeout':
        return 'extraction-timeout'
    if run.get('status') == 'passed' and run.get('exit_code') == 0 and (directory/'actual-snapshot.json').is_file():
        return 'rendering-failed'
    text = str(run.get('stdout', ''))+'\n'+str(run.get('stderr', ''))
    for marker, status in MARKERS:
        if marker in text:
            return status
    return 'unknown-constant' if re.search(r'unknown (?:constant|declaration)', text, re.I) else 'extraction-failed'


def run_shard(project: Path, original: dict, environment: dict, plan: dict, shard_id: str, output: Path,
              *, trust_project: bool = False, dependency_cache: bool = True) -> dict:
    """Build one unchanged environment module once and extract each planned lemma in it."""
    if not trust_project:
        raise PermissionError('Original source execution requires --trust-project')
    bind_original(plan, original, environment)
    shards = [s for s in plan['shards'] if s['id'] == shard_id]
    if len(shards) != 1:
        raise ValueError('Unknown dependency-cone shard')
    shard = shards[0]
    if output.exists():
        raise ValueError('Use a fresh dependency-cone shard output directory')
    output.mkdir(parents=True)
    limits = plan['execution']
    module = shard['module']
    rows = [{'id': lemma_id(module, l['name']), 'name': l['name'], 'status': 'not-attempted',
             'kernel_checked': False} for l in shard['lemmas']]
    report = {'schema': SHARD, 'upstream_commit': PIN, 'cone_plan_sha256': plan['plan_sha256'],
              'shard_id': shard_id, 'module': module, 'execution_limits': limits, 'status': 'preflight',
              'error': None, 'environment_before': None, 'environment_after': None, 'toolchain': None,
              'source_sha256': None, 'build': None, 'lemmas': rows, 'readings_generated': 0,
              'complete': False, 'denominator_name': DENOMINATOR, **FLAGS}
    def save():
        report['statuses'] = dict(sorted(Counter(r['status'] for r in rows).items()))
        write(output/REPORT, report)
    def mark(status, **extra):
        for r in rows:
            r.update(status=status, **extra)
    started = time.monotonic()
    save()
    try:
        if not (project/'lake-manifest.json').is_file():
            raise RuntimeError('The unchanged original source was not restored')
        if not dependency_cache:
            raise RuntimeError('The pinned original dependency cache was not restored')
        if data_digest(exporter_source()) != limits['exporter_sha256']:
            raise ValueError('The installed exporter differs from the planned exporter')
        report['environment_before'] = audit_environment(project, original)
        if report['environment_before'] != environment:
            raise ValueError('Shard environment differs from the independently audited original environment')
        report['status'] = 'running'
        save()
        version = run_bounded(['lake', 'env', 'lean', '--version'], project, timeout=60)
        report['toolchain'] = {'status': version.status, 'version': version.stdout.strip()[:200]}
        source = child(project, shard['source'][len('lean/'):])
        report['source_sha256'] = observed = file_hash(source) if source.is_file() else None
        built = None
        if version.status != 'passed' or not re.search(r'\b'+re.escape(limits['lean_version'])+r'\b', version.stdout):
            mark('toolchain-unavailable')
        elif observed is None:
            mark('source-missing')
        elif observed != shard['source_sha256']:
            mark('source-changed')
        else:
            # One build per shard; every lemma below is extracted against it.
            built = run_bounded(['lake', 'build', module], project, timeout=limits['build_timeout'], max_output=4_000_000)
            write(output/'build.json', asdict(built))
            report['build'] = {'status': built.status, 'exit_code': built.exit_code, 'reason': built.reason,
                               'elapsed_seconds': built.elapsed_seconds, 'log': 'build.json',
                               'log_sha256': file_hash(output/'build.json')}
            if built.status != 'passed':
                mark('build-timeout' if built.reason == 'timeout' else 'build-failed',
                     reason=(built.reason or built.stderr[-2000:])[:2000])
        for row in rows if built is not None and built.status == 'passed' else []:
            remaining = limits['wall_seconds']-(time.monotonic()-started)
            if remaining < 10:
                row['status'] = 'deadline-not-attempted'
                save()
                continue
            row.update(status='extracting', directory='lemmas/'+row['id'])
            save()
            out = output/row['directory']
            out.mkdir(parents=True)
            try:
                receipt = extract_narrative(row['name'], out, module=module, project=project,
                                            version=limits['lean_version'], trust_project=True,
                                            timeout=min(limits['extract_timeout'], remaining),
                                            max_heartbeats=limits['max_heartbeats'])
            except (ValueError, OSError, RuntimeError, RecursionError) as exc:
                receipt = {'status': 'failed', 'errors': [str(exc)[:2000]]}
            if file_hash(source) != observed:
                row.update(status='source-changed', errors=['Original source changed during extraction'])
            elif receipt['status'] == 'passed':
                row.update(status='reading-generated', kernel_checked=True,
                           snapshot_sha256=receipt['snapshot_sha256'],
                           selected_judgements=receipt['selected_judgements'])
            else:
                row.update(status=classify(out), errors=[str(x)[:2000] for x in receipt.get('errors', [])][:5])
            print(row['name'], row['status'], flush=True)
            save()
        report['environment_after'] = audit_environment(project, original)
        if report['environment_after'] != environment:
            raise ValueError('Original source or dependency environment changed during extraction')
        report['readings_generated'] = sum(r['status'] in READ for r in rows)
        report['complete'] = all(r['status'] in READ | DECLINED for r in rows)
        report['status'] = 'complete' if report['complete'] else 'partial'
    except (ValueError, OSError, RuntimeError, RecursionError, subprocess.SubprocessError) as exc:
        report.update(status='failed', error=str(exc)[:4000], complete=False, readings_generated=0)
        # A success without both environment audits is not an original-environment reading.
        for r in rows:
            if r['status'] in READ | TRANSIENT:
                r.update(status='environment-invalidated', kernel_checked=False,
                         unaccepted_snapshot_sha256=r.pop('snapshot_sha256', None))
                r.pop('selected_judgements', None)
    save()
    return report


def _json(path: Path):
    return strict_json(path.read_text(encoding='utf-8'))


def _check_reading(root: Path, row: dict, shard: dict, limits: dict) -> dict:
    """The catalog_inputs.load_proofs checks, plus the exact planned driver for this module."""
    directory = child(root, row['directory'])
    files = {f: child(root, row['directory']+'/'+f) for f in ('snapshot.json', 'receipt.json', 'Extract.lean', 'stdout.txt', 'run.json')}
    if not all(p.is_file() for p in files.values()):
        raise ValueError('Required cone reading artifact is missing')
    record, receipt, run = _json(files['snapshot.json']), _json(files['receipt.json']), _json(files['run.json'])
    if not all(isinstance(x, dict) for x in (record, receipt, run)):
        raise ValueError('Malformed cone reading artifact')
    snap = Snapshot(record)
    name, module, version = row['name'], shard['module'], limits['lean_version']
    driver = files['Extract.lean'].read_text(encoding='utf-8')
    stdout = files['stdout.txt'].read_text(encoding='utf-8')
    if (record['theorem'] != name or receipt.get('theorem') != name or receipt.get('module') != module or
        record['lean_version'] != version or receipt.get('lean_version') != version or
        receipt.get('status') != 'passed' or receipt.get('backend') != 'native' or
        receipt.get('selected_judgements') != record['judgements_checked'] or
        row.get('selected_judgements') != record['judgements_checked'] or
        receipt.get('all_selected_judgements_kernel_checked') is not True or
        receipt.get('path_linkage_checked_in_lean') is not True or row.get('kernel_checked') is not True or
        receipt.get('snapshot_sha256') != snap.sha256 or row.get('snapshot_sha256') != snap.sha256 or
        receipt.get('execution_limits', {}).get('max_heartbeats') != limits['max_heartbeats']):
        raise ValueError('Inconsistent source-bound cone observation: '+name)
    if (receipt.get('source_sha256') != data_digest(driver) or
        driver != extraction_source(name, version=version, module=module, max_heartbeats=limits['max_heartbeats'])):
        raise ValueError('Executed driver is not the planned extraction in this environment module')
    if parse_stream(stdout, theorem=name, version=version).sha256 != snap.sha256:
        raise ValueError('Saved compiler output disagrees with snapshot')
    command = run.get('command', [])
    if (run.get('status') != 'passed' or run.get('exit_code') != 0 or run.get('stdout') != stdout or
        command[:3] != ['lake', 'env', 'lean'] or len(command) != 4):
        raise ValueError('Missing successful native execution observation')
    return {'directory': directory, 'record': record, 'receipt': receipt}


def load_shard(root: Path, plan: dict, environment: dict) -> tuple[dict, list[dict], dict]:
    """Validate one shard report against the plan; return (report, outcome rows, accepted readings)."""
    report = _json(child(root, REPORT))
    if not isinstance(report, dict) or not isinstance(report.get('lemmas'), list) or not all(isinstance(r, dict) for r in report['lemmas']):
        raise ValueError('Malformed dependency-cone shard report')
    shards = {s['id']: s for s in plan['shards']}
    shard = shards.get(report.get('shard_id'))
    if (report.get('schema') != SHARD or report.get('upstream_commit') != PIN or
        report.get('cone_plan_sha256') != plan['plan_sha256'] or shard is None or
        report.get('module') != shard['module'] or report.get('execution_limits') != plan['execution'] or
        report.get('denominator_name') != DENOMINATOR or any(report.get(k) is not v for k, v in FLAGS.items())):
        raise ValueError('Shard report belongs to another plan, shard or denominator')
    rows = report['lemmas']
    if ([r.get('name') for r in rows] != [l['name'] for l in shard['lemmas']] or
        [r.get('id') for r in rows] != [lemma_id(shard['module'], l['name']) for l in shard['lemmas']]):
        raise ValueError('Shard outcomes differ from the planned lemma inventory')
    status = report.get('status')
    if status not in SHARD_STATUSES or any(r.get('status') not in ROW_STATUSES for r in rows):
        raise ValueError('Unknown dependency-cone shard or lemma status')
    if report.get('statuses') != dict(sorted(Counter(r['status'] for r in rows).items())):
        raise ValueError('Shard status counts disagree with its rows')
    finished = status in {'complete', 'partial'}
    read_rows = [r for r in rows if r['status'] in READ]
    if (report.get('readings_generated') != (len(read_rows) if finished else 0) or
        report.get('complete') is not (status == 'complete') or
        (status == 'complete') != all(r['status'] in READ | DECLINED for r in rows) or
        (finished and any(r['status'] in TRANSIENT | {'not-attempted', 'environment-invalidated'} for r in rows)) or
        (status == 'failed' and read_rows)):
        raise ValueError('Shard completion claims disagree with its outcomes')
    referenced = set()
    for r in rows:
        if r['status'] not in READ and (r.get('kernel_checked') is not False or 'snapshot_sha256' in r):
            raise ValueError('An unsuccessful lemma claims a checked snapshot')
        if 'directory' in r:
            if r['directory'] != 'lemmas/'+r['id'] or not child(root, r['directory']).is_dir():
                raise ValueError('Noncanonical or missing cone lemma directory')
            referenced.add(r['id'])
            if r['status'] in DECLINED | ATTEMPT_FAILURES and classify(child(root, r['directory'])) != r['status']:
                raise ValueError('Recorded extraction outcome disagrees with its run observation')
        elif r['status'] in READ | DECLINED | ATTEMPT_FAILURES:
            raise ValueError('An extraction outcome lacks its retained observation')
    lemmas = root/'lemmas'
    if lemmas.is_symlink() or (lemmas.exists() and {p.name for p in lemmas.iterdir()} - referenced):
        raise ValueError('Retained cone output is outside the planned outcomes')
    if not finished:
        # Interrupted or failed: retained for accounting, never accepted as readings.
        return report, rows, {}
    if report.get('environment_before') != environment or report.get('environment_after') != environment:
        raise ValueError('A finished shard lacks the full original environment audit')
    build = report.get('build')
    if build is not None:
        log = child(root, 'build.json')
        if build.get('log') != 'build.json' or not log.is_file() or file_hash(log) != build.get('log_sha256'):
            raise ValueError('Changed or missing module build log')
        observed = _json(log)
        if (not isinstance(observed, dict) or observed.get('command') != ['lake', 'build', shard['module']] or
            any(observed.get(k) != build.get(k) for k in ('status', 'exit_code', 'reason'))):
            raise ValueError('Build log disagrees with the shard report')
    built = build is not None and build.get('status') == 'passed' and build.get('exit_code') == 0 and not build.get('reason')
    if any(r['status'] in READ | DECLINED | ATTEMPT_FAILURES | {'deadline-not-attempted'} for r in rows) and not built:
        raise ValueError('Extraction outcomes require a successful module build')
    toolchain = report.get('toolchain') or {}
    usable = toolchain.get('status') == 'passed' and plan['execution']['lean_version'] in str(toolchain.get('version'))
    kinds = {r['status'] for r in rows}
    whole = kinds & {'toolchain-unavailable', 'source-missing', 'build-failed', 'build-timeout'}
    if whole and (len(kinds) != 1 or (kinds == {'toolchain-unavailable'}) == usable or
                  (kinds == {'source-missing'}) != (report.get('source_sha256') is None) or
                  (kinds & {'build-failed', 'build-timeout'} and
                   (built or build is None or kinds != {'build-timeout' if build.get('reason') == 'timeout' else 'build-failed'}))):
        raise ValueError('A whole-shard outcome disagrees with its observations')
    if read_rows and (not usable or report.get('source_sha256') != shard['source_sha256']):
        raise ValueError('A reading lacks its toolchain or exact source observation')
    accepted = {r['name']: {**_check_reading(root, r, shard, plan['execution']), 'module': shard['module'],
                            'shard_id': shard['id'], 'id': r['id'], 'row': r} for r in read_rows}
    return report, rows, accepted


def reconcile(plan: dict, environment: dict, roots: list[Path], scope: str) -> tuple[dict, dict]:
    """Account for every planned lemma; return (summary, accepted readings by lemma name)."""
    validate_plan(plan)
    if environment.get('environment_sha256') != plan['inputs']['original_environment_sha256']:
        raise ValueError('Reconciliation environment differs from the plan')
    if data_digest(exporter_source()) != plan['execution']['exporter_sha256']:
        raise ValueError('The installed exporter cannot reproduce the planned extraction driver')
    in_scope = {s['id'] for s in scope_shards(plan, scope)}
    seen, outcomes, accepted = set(), {}, {}
    for root in roots:
        report, rows, readings = load_shard(root, plan, environment)
        ident = report['shard_id']
        if ident in seen or ident not in in_scope:
            raise ValueError('Duplicate or out-of-scope dependency-cone shard')
        seen.add(ident)
        finished = report['status'] in {'complete', 'partial'}
        for r in rows:
            outcomes[r['name']] = {'name': r['name'], 'module': report['module'], 'shard_id': ident,
                                   'status': r['status'] if finished else 'shard-'+report['status'],
                                   'last_recorded_status': r['status']}
        accepted.update(readings)
    for s in plan['shards']:
        for l in s['lemmas']:
            if s['id'] not in seen:
                outcomes[l['name']] = {'name': l['name'], 'module': s['module'], 'shard_id': s['id'],
                                       'status': 'shard-artifact-missing' if s['id'] in in_scope else 'not-in-run-scope'}
    if len(outcomes) != plan['denominator']['planned_lemmas']:
        raise ValueError('Reconciled outcomes do not cover the planned lemmas')
    statuses = Counter(o['status'] for o in outcomes.values())
    summary = {'schema': SUMMARY, 'cone_plan_sha256': plan['plan_sha256'], 'scope': scope,
               'denominator_name': DENOMINATOR, 'denominator': plan['denominator'],
               'shards_in_scope': len(in_scope), 'shards_retained': len(seen),
               'missing_shards': sorted(in_scope-seen), 'planned_lemmas': len(outcomes),
               'readings_generated': len(accepted), 'statuses': dict(sorted(statuses.items())),
               'lemmas': [outcomes[n] for n in sorted(outcomes)],
               'reading_index': {n: {'module': a['module'], 'shard_id': a['shard_id'], 'directory': a['row']['directory'],
                                     'snapshot_sha256': a['receipt']['snapshot_sha256']} for n, a in sorted(accepted.items())},
               'deeper_levels_planned': False, **FLAGS}
    return summary, accepted


def reading_map(summary: dict) -> dict[str, dict]:
    """Lemma name -> cone reading location, for citation cross-links."""
    if summary.get('schema') != SUMMARY or summary.get('denominator_name') != DENOMINATOR:
        raise ValueError('Not a dependency-cone summary')
    return dict(summary['reading_index'])
