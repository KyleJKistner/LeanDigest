"""Level-1 dependency cone of the retained readings: plan, shard worker and strict loader.

Most documented theorem targets assemble project lemmas proved elsewhere. The
level-1 cone is every project (OAI) constant that a retained reading applies as
a proof step. Planning reads retained snapshots only and executes nothing. Each
planned lemma is extracted in the unchanged original environment of a module
whose retained reading cites it, so the constant is known to be in scope there.

Cone readings are a SEPARATE denominator. They never enter documented-target
coverage. A missing shard, failed build or declined extraction stays an explicit
outcome. Saved observations establish consistency, not authenticity.
"""
