#!/usr/bin/env python3
"""Review tooling for proofreader/data/glossary.json (docs/GLOSSARY.md).

  review CORPUS -o docs/glossary-review/README.md
      Write the review document: each entry with its quoted statement, notes,
      corpus coverage, two recorded corpus instances and decision checkboxes.
  verify --source mathlib4=DIR [--source lean4=DIR]
      Check that every quoted statement and context excerpt equals the lines
      at its path and line in the given checkouts. Excerpts from unlisted
      sources are reported as unchecked (exit status 3), not as passed.
  mark NAME --reviewer 'Full name' --confirm [--gloss 'revised phrase']
      Record a human review of one entry. Only a person who has compared the
      gloss with the quoted statement should run this.
  remove NAME
      Delete a rejected entry.

The corpus is read, never executed. Rendering here uses the preview mode,
whose glosses are marked as unreviewed and remain explanation gaps.
"""
from __future__ import annotations
import argparse
from collections import Counter, defaultdict
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from proofreader import glossary as G  # noqa: E402
from proofreader.kernel import InvalidExport  # noqa: E402
from proofreader.kernel_io import strict_json  # noqa: E402
from proofreader.model import digest, walk_steps  # noqa: E402
from proofreader.narrative import Narrative  # noqa: E402
from proofreader.reading_kpis import snapshot_paths  # noqa: E402

EXAMPLES = 2
LIMIT = 300  # characters of a recorded corpus formula shown before truncation


def load(path: Path) -> dict:
    data = strict_json(Path(path).read_bytes())
    G.validate(data)
    return data


def save(data: dict, path: Path) -> None:
    G.validate(data)
    Path(path).write_text(json.dumps(data, ensure_ascii=False, indent=1)+'\n', encoding='utf-8')


def corpus_instances(corpus: Path, glossary: G.Glossary) -> tuple[dict, str, int]:
    """Steps in the preview rendering that show each gloss, in snapshot order.

    A proposed gloss shows on a citation gap step with the marker; a reviewed
    one on a reviewed-gloss step, which is explained unless it is a budget cut.
    """
    selection = glossary.select('preview')
    found: dict[str, list[dict]] = defaultdict(list); hashes = []
    for p in snapshot_paths(corpus):
        raw = p.read_bytes(); hashes.append(digest(raw)); record = json.loads(raw)
        n = Narrative(record, glossary=selection)
        d = n.document(title=record['theorem']).declarations[0]
        for s in walk_steps(d.steps):
            f = n.frames[int(s.id.rsplit(':', 1)[1])]
            shown = s.rule == G.REVIEWED_RULE or (s.rule == 'citation' and G.MARKER in s.text)
            if shown and f['head'] in selection:
                found[f['head']].append({'theorem': record['theorem'], 'snapshot': p.parent.relative_to(corpus).as_posix(),
                                         'frame': f['id'], 'conclusion': f['statement'],
                                         'premises': [q['statement'] for q in f['premises']]})
    return found, digest('\n'.join(sorted(hashes))), len(hashes)


def _formula(text: str) -> str:
    if len(text) > LIMIT:
        text = text[:LIMIT]+f'\n… (truncated; {len(text)} characters recorded)'
    return text


def _fence(text: str, lang: str = '') -> list[str]:
    fence = '````' if '```' in text else '```'
    return [fence+lang, *text.split('\n'), fence]


def _count(n: int, noun: str) -> str:
    return f'{n} {noun}' + ('' if n == 1 else 's')


def _picks(instances: list[dict]) -> list[dict]:
    """The first instances from distinct readings, then any others, up to EXAMPLES."""
    first, seen = [], set()
    for x in instances:
        if x['theorem'] not in seen:
            first.append(x); seen.add(x['theorem'])
    rest = [x for x in instances if x not in first]
    return (first+rest)[:EXAMPLES]


def review(glossary: G.Glossary, corpus: Path) -> str:
    found, corpus_sha, readings = corpus_instances(corpus, glossary)
    entries = sorted(glossary.entries.values(), key=lambda e: (-len(found[e['name']]), e['name']))
    status = Counter(e['status'] for e in entries)
    by_model = sum(e['proposed_by'] == 'model' for e in entries)
    total = sum(len(found[e['name']]) for e in entries)
    out = ['# Glossary review', '',
           'Generated by `scripts/glossary_review.py review`; do not edit by hand. Glossary sha256 `'+glossary.sha256+'`; '
           f'corpus sha256 `{corpus_sha}` ({readings} retained snapshots).', '',
           f'The glossary has {len(entries)} entries: {status["proposed"]} proposed and {status["reviewed"]} reviewed; '
           f'{by_model} were proposed by a model. A proposed gloss never changes a default reading; in the preview mode '
           'it is shown with the marker "'+G.MARKER+'" and the step remains an explanation gap. In a reading, the '
           'constant\'s name may be shortened as the notation legend states.', '',
           f'Coverage counts the steps of the preview rendering of the corpus that show the gloss: {total} steps in '
           'total. For a proposed entry these are library-citation gap steps; reviewing the entry makes them explained, '
           'except where the cited frame is a budget cut. For a reviewed entry they are reviewed-gloss steps.', '',
           '## Review procedure', '',
           'For each entry, compare the gloss with the quoted statement and its context, and with the recorded corpus '
           'instances. The gloss must describe what the declaration proves and claim nothing more; it may leave '
           'hypotheses to the premises and instance facts that the reading lists below the step. Then record the '
           'decision:', '',
           '- Accept: `python scripts/glossary_review.py mark NAME --reviewer "Full name" --confirm`',
           '- Accept with a revised gloss: add `--gloss "revised phrase"` to the same command.',
           '- Reject: `python scripts/glossary_review.py remove NAME`', '',
           'Accepting changes default readings, so the reading-KPI baseline must be regenerated in the same change.', '',
           '## Summary', '', '| Constant | Gloss | Status | Steps | Readings |', '|---|---|---|---:|---:|']
    for e in entries:
        x = found[e['name']]
        cell = e['gloss'].replace('|', '\\|')
        out.append(f"| `{e['name']}` | {cell} | {e['status']} | {len(x)} | {len({i['theorem'] for i in x})} |")
    out += ['', '## Entries', '']
    for e in entries:
        x = found[e['name']]; st = e['statement']; src = glossary.data['sources'][st['source']]
        link = src['repository']+'/blob/'+src['revision']+'/'+st['path']+'#L'+str(st['line'])
        out += ['### `'+e['name']+'`', '', '- Gloss: '+e['gloss'], '- Step text once reviewed: By '+e['gloss']+' ('+e['name']+'):',
                f"- Status: {e['status']}; proposed by {e['proposed_by']}; reviewer: {e['reviewed_by'] or 'none'}",
                '- Coverage: '+_count(len(x), 'citation gap step' if e['status'] == 'proposed' else 'reviewed-gloss step')
                +' in '+_count(len({i['theorem'] for i in x}), 'reading'),
                f"- Statement: {st['source']} `{st['path']}:{st['line']}` ([source]({link}))", '']
        out += _fence(st['text'], 'lean')
        if st['context']:
            out += ['', 'Context (exact source lines):', '']
            out += _fence('\n'.join('-- '+c['path']+':'+str(c['line'])+'\n'+c['text'] for c in st['context']), 'lean')
        if e['notes']:
            out += ['', 'Notes: '+e['notes']]
        out += ['', 'Corpus instances (recorded conclusion and premises of the cited frame):', '']
        for k, i in enumerate(_picks(x), 1):
            out.append(f"{k}. `{i['theorem']}`, snapshot `{i['snapshot']}`, frame {i['frame']}")
            out += ['', *('   '+line for line in _fence(_formula(i['conclusion'])))]
            if i['premises']:
                out += ['', '   Premises:', '', *('   '+line for line in _fence('\n'.join(_formula(q) for q in i['premises'])))]
            out.append('')
        if not x:
            out += ['No corpus step shows this gloss.', '']
        out += ['Decision:', '', '- [ ] Accept', '- [ ] Accept with revised gloss: ', '- [ ] Reject: ', '']
    return '\n'.join(out).rstrip('\n')+'\n'


def verify(glossary: G.Glossary, roots: dict[str, Path]) -> dict:
    """Compare every quoted excerpt with its source lines."""
    checked, mismatches, unchecked = 0, [], Counter()
    cache: dict[tuple[str, str], list[str] | None] = {}
    for e in glossary.entries.values():
        for x in [e['statement'], *e['statement']['context']]:
            if x['source'] not in roots:
                unchecked[x['source']] += 1
                continue
            key = (x['source'], x['path'])
            if key not in cache:
                f = roots[x['source']]/x['path']
                cache[key] = f.read_text(encoding='utf-8').split('\n') if f.is_file() else None
            lines = cache[key]; want = x['text'].split('\n')
            got = None if lines is None else lines[x['line']-1:x['line']-1+len(want)]
            checked += 1
            if got != want:
                mismatches.append(e['name']+': '+x['source']+' '+x['path']+':'+str(x['line']))
    return {'excerpts_checked': checked, 'mismatches': mismatches, 'unchecked_by_source': dict(sorted(unchecked.items()))}


def mark(data: dict, name: str, reviewer: str, gloss: str | None = None) -> dict:
    entry = next((e for e in data['entries'] if e['name'] == name), None)
    if entry is None:
        raise InvalidExport('No glossary entry named '+name)
    if not reviewer.strip():
        raise InvalidExport('A review needs the reviewer\'s name')
    entry['status'] = 'reviewed'; entry['reviewed_by'] = reviewer.strip()
    if gloss is not None and gloss != entry['gloss']:
        # proposed_by names who proposed the entry; keep the wording the reviewer replaced.
        entry['notes'] = (entry['notes']+' ' if entry['notes'] else '')+'Gloss revised at review; proposed: '+entry['gloss']+'.'
        entry['gloss'] = gloss
    G.validate(data)
    return data


def remove(data: dict, name: str) -> dict:
    kept = [e for e in data['entries'] if e['name'] != name]
    if len(kept) == len(data['entries']):
        raise InvalidExport('No glossary entry named '+name)
    data['entries'] = kept
    G.validate(data)
    return data


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    p.add_argument('--glossary', type=Path, default=G.PATH, help='Glossary file (default: the packaged one)')
    sub = p.add_subparsers(dest='command', required=True)
    r = sub.add_parser('review', help='Write the review document from a snapshot corpus')
    r.add_argument('corpus', type=Path); r.add_argument('-o', '--output', type=Path, required=True)
    v = sub.add_parser('verify', help='Check quoted statements against source checkouts')
    v.add_argument('--source', action='append', default=[], metavar='NAME=DIR')
    m = sub.add_parser('mark', help='Record a human review of one entry')
    m.add_argument('name'); m.add_argument('--reviewer', required=True); m.add_argument('--gloss')
    m.add_argument('--confirm', action='store_true', help='I compared the gloss with the quoted statement')
    d = sub.add_parser('remove', help='Delete a rejected entry')
    d.add_argument('name')
    a = p.parse_args(argv)
    try:
        if a.command == 'review':
            a.output.parent.mkdir(parents=True, exist_ok=True)
            a.output.write_text(review(G.Glossary(load(a.glossary)), a.corpus), encoding='utf-8')
            print(a.output); return 0
        if a.command == 'verify':
            roots = {}
            for item in a.source:
                name, _, path = item.partition('=')
                if not name or not path:
                    raise InvalidExport('Expected --source NAME=DIR')
                roots[name] = Path(path)
            result = verify(G.Glossary(load(a.glossary)), roots)
            print(json.dumps(result, indent=2, ensure_ascii=False))
            # 1: a quoted excerpt differs; 3: some excerpts were not checked (no checkout given).
            return 1 if result['mismatches'] or not result['excerpts_checked'] else 3 if result['unchecked_by_source'] else 0
        if a.command == 'mark':
            if not a.confirm:
                raise InvalidExport('Pass --confirm after comparing the gloss with the quoted statement')
            save(mark(load(a.glossary), a.name, a.reviewer, a.gloss), a.glossary)
        else:
            save(remove(load(a.glossary), a.name), a.glossary)
        print(a.command+'ed '+a.name if a.command == 'mark' else 'removed '+a.name)
        return 0
    except (InvalidExport, OSError, ValueError) as exc:
        print('glossary_review: '+str(exc), file=sys.stderr)
        return 2


if __name__ == '__main__':
    raise SystemExit(main())
